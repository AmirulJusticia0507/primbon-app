CREATE TABLE IF NOT EXISTS petung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hari TEXT NOT NULL CHECK (hari IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu', 'Minggu')),
    pasaran TEXT NOT NULL CHECK (pasaran IN ('Legi', 'Pahing', 'Pon', 'Wage', 'Kliwon')),
    nilai_hari INTEGER NOT NULL CHECK (
        (hari = 'Minggu' AND nilai_hari = 5) OR
        (hari = 'Senin' AND nilai_hari = 4) OR
        (hari = 'Selasa' AND nilai_hari = 3) OR
        (hari = 'Rabu' AND nilai_hari = 7) OR
        (hari = 'Kamis' AND nilai_hari = 8) OR
        (hari = 'Jumat' AND nilai_hari = 6) OR
        (hari = 'Sabtu' AND nilai_hari = 9)
    ),
    nilai_pasaran INTEGER NOT NULL CHECK (
        (pasaran = 'Legi' AND nilai_pasaran = 5) OR
        (pasaran = 'Pahing' AND nilai_pasaran = 9) OR
        (pasaran = 'Pon' AND nilai_pasaran = 7) OR
        (pasaran = 'Wage' AND nilai_pasaran = 4) OR
        (pasaran = 'Kliwon' AND nilai_pasaran = 8)
    ),
    CONSTRAINT petung_hari_pasaran_key UNIQUE (hari, pasaran)
);
